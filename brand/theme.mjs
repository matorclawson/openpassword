// Generate the Tailwind v4 equivalent of the shared preset from its source tokens.
import {writeFileSync,readFileSync} from "node:fs";
import {colorTokens,fontTokens,shadowTokens,radiusTokens,gradientTokens} from "./tokens.ts";
const kebab=name=>name.replace(/[A-Z]/g,c=>"-"+c.toLowerCase());
const lines=(group,kind,format)=>Object.entries(group).map(([name,value])=>"  --"+kind+kebab(name)+": "+format(value)+";").join("\n");
const css="/* Generated by node brand/theme.mjs from brand/tokens.ts. */\n@theme static {\n"+
  [lines(colorTokens,"color-",v=>"hsl("+v+")"),lines(fontTokens,"font-",String),lines(shadowTokens,"shadow-",String),
  "  --radius-lg: "+radiusTokens.base+";\n  --radius-md: calc(var(--radius-lg) - 2px);\n  --radius-sm: calc(var(--radius-lg) - 4px);\n  --radius-2xl: 1.25rem;\n  --radius-3xl: 1.5rem;",
  lines(gradientTokens,"background-image-",String)].join("\n")+"\n}\n";
const file=new URL("./theme.css",import.meta.url);
if(process.argv.includes("--check")){if(css!==readFileSync(file,"utf8"))throw Error("Regenerate brand/theme.css");}
else writeFileSync(file,css);
